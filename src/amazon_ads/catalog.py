"""The operation catalog: every operation in every Ads API spec Amazon publishes.

Generated by ``scripts/generate_catalog.py`` from Amazon's OpenAPI specs. Each entry
records the HTTP method, path template, parameters and the vendor media types Amazon
expects, which is what :meth:`ProfileClient.call` needs to send any operation correctly.

Two things are applied on top of the generated file when it loads, so regenerating it
from Amazon's specs cannot undo them:

* :data:`CORRECTIONS`: media types the live API needs where the spec says otherwise.
  The corrected :attr:`Operation.accept` is what gets sent, :attr:`Operation.note` says
  why, and :attr:`Operation.accepts` still lists what the spec documents.
* Operations this client cannot send carry :attr:`Operation.unsupported_reason`. Today
  that is every tool of Amazon's hosted Ads MCP server, which Amazon publishes as OpenAPI
  files beside the Ads API specs. :func:`search` leaves them out and
  :meth:`ProfileClient.call` refuses them.

Look operations up by full id (``"sponsored-products:ListSponsoredProductsKeywords"``), by
bare operation id when it is unique across APIs, or search with :func:`search`.
"""

from __future__ import annotations

import json
import numbers
import re
from collections.abc import Mapping
from dataclasses import dataclass
from functools import cache
from importlib import resources
from typing import Any, Final
from urllib.parse import quote

from amazon_ads.errors import UnsupportedOperationError
from amazon_ads.transport import READ_ONLY_POST_SUFFIXES

# A POST counts as read-only when its operation id, or one of its path segments, starts
# with one of these words: listCampaigns, /sp/keywords/list, /adsApi/v1/query/targets,
# /sp/targets/bid/recommendations. Only the start of an id or segment is compared. A
# bare substring test matched "get" inside "targets", "budgetRules" and
# "targetPromotionGroups", and "search" inside "audienceResearch", so creates such as
# POST /sp/targets were treated as reads: the MCP server called them without a plan and
# the transport retried them after a 5xx, which can create every target twice.
READ_WORDS = ("list", "query", "recommendation", "search", "get", "describe", "history")

# A POST whose operation id or any path segment starts with one of these is never
# read-only, even when a read word or a read-only suffix also matches. Some writes carry
# both: createQueryBasedAudience is POST /amc/audiences/query, and the /query suffix
# alone would let the MCP server start an audience build without approval.
WRITE_WORDS = ("create", "update", "delete", "archive")

# Path endings that mark a POST read-only. They include every suffix the transport
# treats as safe to resend after a 5xx (READ_ONLY_POST_SUFFIXES), so ProfileClient.call()
# never refuses a retry that ProfileClient.request() would make for the same path. The
# catalog goes further than the transport: "/query" and the read words above make more
# POSTs read-only, and call() retries those while a bare request() to the same path does
# not. The transport keeps the shorter list because it decides from the path alone, with
# no operation id, and no request the library builds itself goes to a /query path.
READ_ONLY_PATH_SUFFIXES = (*READ_ONLY_POST_SUFFIXES, "/query")


@dataclass(frozen=True)
class Operation:
    id: str
    api: str
    operation_id: str
    method: str
    path: str
    summary: str
    tags: tuple[str, ...]
    deprecated: bool
    path_params: tuple[str, ...]
    query: tuple[dict[str, Any], ...]
    headers: tuple[dict[str, Any], ...]
    content_type: str | None
    accept: str | None
    content_types: tuple[str, ...]
    accepts: tuple[str, ...]
    has_body: bool
    note: str | None = None
    """Why this entry differs from Amazon's spec, when a :data:`CORRECTIONS` entry applies."""
    unsupported_reason: str | None = None
    """Why this client cannot send the operation, or None when it can."""

    @property
    def read_only(self) -> bool:
        """True for operations that change nothing: GETs, and POSTs whose path or id
        says they list, query or recommend (see ``READ_WORDS``) and nothing says they
        create, update, delete or archive (see ``WRITE_WORDS``).

        The MCP server's ``call_operation`` refuses every operation for which this is
        False, ``adsctl ops call`` asks before sending one, and
        :meth:`ProfileClient.call` retries an operation after a 5xx or timeout only
        when this is True."""
        if self.method == "GET":
            return True
        if self.method != "POST":
            return False
        path = self.path.rstrip("/")
        op = self.operation_id.lower()
        segments = [s.lower() for s in path.split("/") if s and not s.startswith("{")]
        if op.startswith(WRITE_WORDS) or any(s.startswith(WRITE_WORDS) for s in segments):
            return False
        return (
            path.endswith(READ_ONLY_PATH_SUFFIXES)
            or op.startswith(READ_WORDS)
            or any(s.startswith(READ_WORDS) for s in segments)
        )

    def ensure_sendable(self) -> None:
        """Raise :class:`UnsupportedOperationError` if this client cannot send it."""
        if self.unsupported_reason:
            raise UnsupportedOperationError(self.unsupported_reason)

    def format_path(self, path_params: Mapping[str, Any] | None = None) -> str:
        """The path with every ``{name}`` placeholder replaced by its value.

        Each value fills exactly one path segment and reaches Amazon as given; see
        :func:`path_segment` for the values refused with ``ValueError``. Placeholders are
        read from the path template itself rather than from :attr:`path_params`, so one
        that a spec forgot to declare is still required and checked. Names that match no
        placeholder are ignored.
        """
        params = path_params or {}
        names = dict.fromkeys(_PLACEHOLDER.findall(self.path))
        missing = [name for name in names if name not in params]
        if missing:
            raise ValueError(f"{self.id} needs path parameters: {', '.join(missing)}")
        return _PLACEHOLDER.sub(
            lambda m: path_segment(self.id, m.group(1), params[m.group(1)]), self.path
        )


# A "{name}" placeholder in a path template, as Amazon's specs write them.
_PLACEHOLDER = re.compile(r"\{([^{}]+)\}")

# Characters sent unencoded inside a path segment, beyond the letters, digits and "-._~"
# that quote() never encodes. They are delimiters RFC 3986 (section 3.3, "pchar") allows
# in a segment, and Amazon ids use some of them, such as the "." and ":" in
# "amzn1.ads-account.g.EXAMPLE"; a server reads them the same encoded or not. Two pchar
# delimiters are left out because some servers give them a meaning: Java servlet
# containers cut ";anything" off a segment before routing, so a raw "..;x" would be read
# as "..", and a server that decodes paths the way HTML forms are decoded reads "+" as a
# space. Every other character, "%" included, is percent-encoded, so Amazon decodes the
# segment back to exactly the value given.
_SEGMENT_SAFE = "!$&'()*,=:@"

# "/" starts a new segment, "?" a query and "#" a fragment. Some servers also read "\"
# as "/". No Amazon id contains any of them.
_SEPARATORS = ("/", "\\", "?", "#")

# A segment that is empty or only dots changes which path the request reaches: httpx
# resolves "/a/b/../c" to "/a/c" before sending, and some servers drop trailing dots and
# spaces, which turns "..." or ".. " into "..".
_DOTS_AND_SPACES = re.compile(r"[\s.]*")

# A percent-escape such as "%2F" or "%20". Callers pass plain values, so an escape is
# either a value encoded by mistake, which would reach Amazon still encoded and name the
# wrong thing, or an attempt to slip a separator past the checks below to a server that
# decodes the path before routing.
_PERCENT_ESCAPE = re.compile(r"%[0-9A-Fa-f]{2}")

# ASCII control characters. No id contains one, and a server that stops reading at NUL
# would see "..%00" as "..".
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")


def path_segment(operation_id: str, name: str, value: Any) -> str:
    """``value`` percent-encoded as one path segment, or ``ValueError`` naming ``name``.

    :meth:`Operation.format_path` fills every path parameter through this, and code that
    builds a path by hand, such as a raw :meth:`ProfileClient.request` call, can use it
    the same way. ``operation_id`` and ``name`` only label the error.

    The value must be a string or an integer. It is refused, rather than encoded into
    something harmless, when it is percent-encoded, contains "/", "\\", "?", "#" or a
    control character, or is empty or only dots and spaces (before its first ";" too):
    a value like that is a mistake or an attack, never an id. Unchecked,
    ``{"brandEntityId": "../sp/targets?x="}`` would turn
    ``POST /stores/{brandEntityId}/insights`` into ``POST /sp/targets``, a write sent as
    though it were the read that the caller, or the MCP server's read-only guard,
    approved.
    """

    def refuse(reason: str) -> ValueError:
        return ValueError(
            f"{operation_id}: path parameter {name}={value!r} {reason}; pass the plain, "
            "unencoded value of one path segment"
        )

    # str() would send None as "None", True as "True", 1e17 as "1e+17" and b"7" as "b'7'",
    # each as though it were an id. numbers.Integral also admits numpy integers, which is
    # what ids read from a pandas DataFrame are. bool is an int, so it is refused by name.
    if isinstance(value, bool) or not isinstance(value, str | numbers.Integral):
        raise refuse("must be a string or an integer id")
    text = str(value)
    if _PERCENT_ESCAPE.search(text):
        raise refuse("is percent-encoded")
    if any(sep in text for sep in _SEPARATORS):
        raise refuse("contains '/', '\\', '?' or '#'")
    if _CONTROL.search(text):
        raise refuse("contains a control character")
    if _DOTS_AND_SPACES.fullmatch(text):
        raise refuse("is empty or only dots and spaces")
    # Java servlet containers decode "%3B" to ";" and then cut ";anything" off the
    # segment before routing, so what comes before the first ";" must pass the same test.
    if _DOTS_AND_SPACES.fullmatch(text.partition(";")[0]):
        raise refuse("has nothing but dots and spaces before its first ';'")
    try:
        # No escape is left in the value, so every "%" is literal and goes out as "%25":
        # Amazon decodes the segment once to the value itself, and decoding it again
        # changes nothing.
        return quote(text, safe=_SEGMENT_SAFE)
    except UnicodeEncodeError:
        # A lone surrogate such as "\ud800" has no UTF-8 form.
        raise refuse("is not valid Unicode text") from None


@dataclass(frozen=True)
class Api:
    slug: str
    title: str
    version: str
    source: str
    section: str | None


@dataclass(frozen=True)
class Correction:
    """The Accept type to send where the one Amazon's spec documents is refused live."""

    accept: str
    note: str


# Keyed by full operation id. Every entry was found by calling the live API, and the
# matching behavior is described in notes.py. A test fails when an id stops naming an
# operation (Amazon renamed it, so the correction would silently stop applying) or when
# the spec starts documenting the corrected type (the correction may no longer be needed).
CORRECTIONS: Final[Mapping[str, Correction]] = {
    "advertising-billing:getAdvertiserInvoices": Correction(
        accept="application/json",
        note="Amazon answers the spec's application/vnd.invoices.v1.1+json with 406 Not "
        "Acceptable and an empty body, so application/json is sent. The response is "
        'wrapped as {"status": "success", "payload": {...}} (found 2026-10-18).',
    ),
    "advertising-billing:getInvoice": Correction(
        accept="application/json",
        note="Amazon answers the spec's application/vnd.invoice.v1.1+json with 406 Not "
        "Acceptable and an empty body, so application/json is sent. The response is "
        'wrapped as {"status": "success", "payload": {...}} (found 2026-10-18).',
    ),
}

# Ads API operations that do what a hosted MCP tool does, named in that tool's refusal.
# Each target was called live with this client and must stay sendable and read-only.
INSTEAD_OF_MCP_TOOL: Final[Mapping[str, str]] = {
    "mcp-billing:list_invoices": "advertising-billing:getAdvertiserInvoices",
    "mcp-billing:list_invoice_summaries": "advertising-billing:GetBillingInvoiceSummaries",
}

# scripts/fetch_specs.py names an API "mcp-..." when its spec sits in the mcp/ folder of
# Amazon's docs, after an optional "dest/" or "openapi/en-us/dest/" prefix. This matches
# that folder in the URL shapes Amazon's docs use. The test that ties every POST /mcp/
# path to a refusal is the backstop if Amazon moves the files somewhere else.
_HOSTED_MCP_TOOL_FOLDER = re.compile(r"/en-us/(?:(?:openapi/en-us/)?dest/)?mcp/")


def is_hosted_mcp_tool(source: str) -> bool:
    """True when an API's spec (by its source URL) lists tools of Amazon's hosted Ads MCP
    server rather than Ads API endpoints. Those specs name no server and document no
    responses, and every operation in them is ``POST /mcp/<tool_name>``, a path the Ads
    API hosts do not serve."""
    return _HOSTED_MCP_TOOL_FOLDER.search(source) is not None


def _mcp_tool_refusal(op_id: str, method: str, path: str) -> str:
    instead = INSTEAD_OF_MCP_TOOL.get(op_id)
    pointer = (
        f"Use {instead} instead."
        if instead
        else "Search the catalog for an Ads API operation that does the same."
    )
    return (
        f"{op_id} is a tool of Amazon's hosted Ads MCP server (beta), not an Ads API "
        f"endpoint, so this client does not send it. {pointer} The Ads API hosts have no "
        f"route for {method} {path}: they answer it, as they answer any path they do not "
        'serve, with 403 "Invalid key=value pair (missing equal-sign) in Authorization '
        "header\". Amazon's MCP docs say MCP clients reach these tools at "
        "https://advertising-ai.amazon.com/mcp (advertising-ai-eu.amazon.com and "
        "advertising-ai-fe.amazon.com for EU and FE); this library has not tried that server."
    )


@cache
def _load() -> tuple[dict[str, Api], dict[str, Operation]]:
    raw = resources.files("amazon_ads._generated").joinpath("catalog.json").read_text()
    data = json.loads(raw)
    apis = {slug: Api(slug=slug, **info) for slug, info in data["apis"].items()}
    ops: dict[str, Operation] = {}
    for entry in data["operations"]:
        correction = CORRECTIONS.get(entry["id"])
        unsupported = (
            _mcp_tool_refusal(entry["id"], entry["method"], entry["path"])
            if is_hosted_mcp_tool(apis[entry["api"]].source)
            else None
        )
        ops[entry["id"]] = Operation(
            id=entry["id"],
            api=entry["api"],
            operation_id=entry["operation_id"],
            method=entry["method"],
            path=entry["path"],
            summary=entry["summary"],
            tags=tuple(entry["tags"]),
            deprecated=entry["deprecated"],
            path_params=tuple(entry["path_params"]),
            query=tuple(entry["query"]),
            headers=tuple(entry["headers"]),
            content_type=entry["content_type"],
            accept=correction.accept if correction else entry["accept"],
            content_types=tuple(entry["content_types"]),
            accepts=tuple(entry["accepts"]),
            has_body=entry["has_body"],
            note=correction.note if correction else None,
            unsupported_reason=unsupported,
        )
    return apis, ops


def apis() -> dict[str, Api]:
    return dict(_load()[0])


def operations(api: str | None = None) -> list[Operation]:
    ops = _load()[1].values()
    return [op for op in ops if api is None or op.api == api]


def get(operation: str) -> Operation:
    """Find an operation by ``"api:operationId"``, or by bare operation id if unique.

    Operations this client cannot send are returned too, so their
    :attr:`~Operation.unsupported_reason` can explain why."""
    ops = _load()[1]
    if operation in ops:
        return ops[operation]
    matches = [op for op in ops.values() if op.operation_id == operation]
    if len(matches) == 1:
        return matches[0]
    if matches:
        ids = ", ".join(op.id for op in matches)
        raise KeyError(f"{operation!r} is ambiguous; use one of: {ids}")
    raise KeyError(f"No operation {operation!r}. Try amazon_ads.catalog.search().")


def search(
    text: str, *, api: str | None = None, limit: int = 25, include_unsupported: bool = False
) -> list[Operation]:
    """Operations whose id, path, summary or tags contain every word of ``text``.

    Operations this client cannot send are left out unless ``include_unsupported`` is
    true or ``api`` names their API, so a search scoped to one of them returns them, each
    with its :attr:`~Operation.unsupported_reason`, instead of nothing.
    """
    words = text.lower().split()
    show_unsupported = include_unsupported or api is not None
    found = []
    for op in operations(api):
        if op.unsupported_reason and not show_unsupported:
            continue
        haystack = " ".join([op.id, op.path, op.summary, *op.tags]).lower()
        if all(w in haystack for w in words):
            found.append(op)
    found.sort(key=lambda op: (op.deprecated, op.api, op.path))
    return found[:limit]
